#!/usr/bin/env python3
"""Embed the editable multilingual phrase grammar; no runtime Python dependency."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'data/dialogue_catalogue.json').read_text(encoding='utf-8'))
q = lambda s: json.dumps(s, ensure_ascii=False)
rows = []
for code, pack in data.items():
    assert len(pack['prefix']) == len(pack['tail']) == 6
    assert len(pack['empty']) == 3 and len(pack['body']) == 23
    assert all(len(row) == 3 for row in pack['body'])
    assert len(pack['ack']) == len(pack['plan']) == 3
    arrays = [q(code)] + ['{' + ','.join(map(q,pack[key])) + '}' for key in ['prefix','tail','empty','ack','plan']]
    arrays.append('{' + ',\n'.join('{' + ','.join(map(q,row)) + '}' for row in pack['body']) + '}')
    rows.append('{' + ',\n'.join(arrays) + '}')
output = '// Generated by tools/build_dialogue_catalogue.py. GPL-2.0-or-later.\nstatic constexpr LanguagePack catalogue[] = {\n' + ',\n'.join(rows) + '\n};\n'
(root / 'src/copycat/dialogue_catalogue.inc').write_text(output,encoding='utf-8')
print(f'{len(data)} languages; {len(data) * 90} source fragments')
